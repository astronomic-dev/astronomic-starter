/**
 * Writes src/styles/looks.scoped.css: every look in src/styles/looks/ (its kit preset, then its own font lines),
 * scoped to `:root[data-look="<look>"]`, for the home page's demo switch (src/components/LookSwitch.astro).
 *
 *   pnpm looks:scope            write the file
 *   pnpm looks:scope --check    exit 1 when the committed file is out of date (scripts/scope-looks.test.mjs runs it)
 *
 * Each `:root` in a selector gains `[data-look="<look>"]`, so the dark forms stay dark forms:
 * `:root:not([data-theme="light"])` inside the prefers-color-scheme query and `:root[data-theme="dark"]`.
 * Comments are dropped. No dependencies. The real look switch stays the one line in src/styles/global.css; delete
 * LookSwitch.astro and looks.scoped.css to drop the demo.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const looksDir = new URL("src/styles/looks/", root);
export const OUT = fileURLToPath(new URL("src/styles/looks.scoped.css", root));

const stripComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, "");

/** A look file's CSS with its preset inlined where the preset's @import stood. */
function lookCss(name) {
	const own = readFileSync(new URL(`${name}.css`, looksDir), "utf8");
	return stripComments(own).replace(/@import\s+["']([^"']+)["'];/g, (_, spec) => {
		const path = fileURLToPath(import.meta.resolve(spec));
		return stripComments(readFileSync(path, "utf8"));
	});
}

/** The CSS, with every `:root` scoped to the look, and blank lines squeezed. */
export function scopeLook(css, name) {
	if (/@import/.test(css)) throw new Error(`${name}: an @import is left after inlining the preset`);
	return css
		.replace(/:root(?!\[data-look)/g, `:root[data-look="${name}"]`)
		.replace(/\n\s*\n+/g, "\n")
		.trim();
}

export function looks() {
	return readdirSync(looksDir)
		.filter((f) => f.endsWith(".css"))
		.map((f) => f.slice(0, -4))
		.sort();
}

export function scopedCss() {
	const head = [
		"/*",
		" * Generated by scripts/scope-looks.mjs (pnpm looks:scope) from src/styles/looks/ and the kit presets. Do not edit.",
		" * Every look, scoped to :root[data-look=\"<look>\"], for the home page's demo switch (src/components/LookSwitch.astro,",
		" * which imports this file). Your site's look is the one line in src/styles/global.css.",
		" */",
	].join("\n");
	const blocks = looks().map((name) => `/* ${name} */\n${scopeLook(lookCss(name), name)}`);
	return `${head}\n${blocks.join("\n\n")}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
	const css = scopedCss();
	if (process.argv.includes("--check")) {
		let committed = "";
		try {
			committed = readFileSync(OUT, "utf8");
		} catch {}
		if (committed !== css) {
			console.error("src/styles/looks.scoped.css is out of date: run pnpm looks:scope");
			process.exit(1);
		}
		console.log("looks.scoped.css is up to date");
	} else {
		writeFileSync(OUT, css);
		console.log(`Wrote ${OUT} (${looks().join(", ")})`);
	}
}
